# -*- coding: utf-8 -*-
"""
공공데이터 CSV → 웹페이지가 읽을 JSON

수업 2회차 "엑셀이 JSON이 되기까지" 시연에 쓰는 스크립트입니다.
학생은 이걸 실행하지 않습니다. 강사가 화면으로 보여주고, 결과 JSON만 나눠줍니다.

열이 44개인 표에서 필요한 것만 골라, 한 줄을 { } 하나로 바꿉니다.

  python3 convert.py

한 줄로 요약하면: 엑셀 표의 한 줄이 JSON의 { } 하나가 됩니다.
"""

import csv, io, json, os

여기 = os.path.dirname(os.path.abspath(__file__))


def 읽기(파일명):
    """CSV 를 읽어 머리글과 나머지 줄로 나눕니다."""
    경로 = os.path.join(여기, 파일명)
    바이트 = open(경로, "rb").read()
    try:
        글자 = 바이트.decode("utf-8")
    except UnicodeDecodeError:
        # 공공데이터포털에서 새로 받은 파일은 UTF-8 이 아닐 수 있습니다
        글자 = 바이트.decode("euc-kr")
    표 = list(csv.reader(io.StringIO(글자)))
    return 표[0], 표[1:]                             # 머리글, 나머지


# ─────────────────────────────────────────────────────────────
#  ① 지하철 혼잡도
#     원본: 요일 / 호선 / 역번호 / 출발역 / 상하구분 + 시간대 39칸
#     열이 44개인데, 시간대 39칸은 "한 칸에 하나씩"이 아니라
#     사실 같은 종류의 값이 옆으로 늘어선 것입니다. 묶어줍니다.
# ─────────────────────────────────────────────────────────────
def 지하철():
    머리글, 줄들 = 읽기("subway.csv")
    시간열 = 머리글[5:]                               # '5시30분' … '00시30분'

    # '5시30분' → '05:30' 으로 다듬습니다. 화면에 그대로 쓸 이름이니까요.
    def 시각(이름):
        시, 분 = 이름.replace("분", "").split("시")
        return f"{int(시):02d}:{int(분):02d}"

    시간표 = [시각(이름) for 이름 in 시간열]

    결과 = []
    for 줄 in 줄들:
        값들 = [float(v.strip()) for v in 줄[5:]]
        가장혼잡 = max(값들)
        결과.append({
            "요일": 줄[0].strip(),
            "호선": 줄[1].strip(),
            "역명": 줄[3].strip(),
            "방향": 줄[4].strip(),
            "시간대": dict(zip(시간표, 값들)),
            # 아래 둘은 원본 CSV에 없습니다. 계산해서 넣은 값입니다.
            "최대혼잡": 가장혼잡,
            "최대시각": 시간표[값들.index(가장혼잡)],
        })
    return {"시간표": 시간표, "자료": 결과}


# ─────────────────────────────────────────────────────────────
#  ② 공공자전거 신규가입자
#     '회원구분'은 값이 '회원-내국인' 하나뿐이라 버립니다.
#     열이 있다고 다 쓸모 있는 건 아닙니다.
# ─────────────────────────────────────────────────────────────
연령순서 = ["~10대", "20대", "30대", "40대", "50대", "60대", "70대이상", "기타"]


def 자전거():
    머리글, 줄들 = 읽기("bike.csv")
    결과 = []
    for 줄 in 줄들:
        년월 = 줄[0]                                   # '202601'
        결과.append({
            "년월": f"{년월[:4]}-{년월[4:]}",           # '2026-01'
            "월": int(년월[4:]),
            "연령대": 줄[2],
            "성별": "여성" if 줄[3] == "F" else "남성",
            "가입건수": int(줄[4]),
        })
    # 가나다순으로 정렬하면 '~10대'가 맨 뒤로 갑니다. 나이 순으로 다시 세웁니다.
    결과.sort(key=lambda x: (x["월"], 연령순서.index(x["연령대"]), x["성별"]))
    return {"연령순서": 연령순서, "자료": 결과}


def 저장(이름, 내용):
    경로 = os.path.join(여기, 이름)
    with open(경로, "w", encoding="utf-8") as f:
        json.dump(내용, f, ensure_ascii=False, separators=(",", ":"))
    크기 = os.path.getsize(경로)
    print(f"  {이름:16} {len(내용['자료']):5,}건  {크기/1024:8,.0f} KB")


if __name__ == "__main__":
    print("\n  CSV → JSON 변환\n")
    저장("subway.json", 지하철())
    저장("bike.json", 자전거())
    print("\n  끝났습니다. 이 JSON을 웹페이지 폴더에 넣으면 됩니다.\n")
